import { access } from 'node:fs/promises';
import { expect, test } from '@playwright/test';
import { Verifier } from '@pact-foundation/pact';
import { buildApp } from '../../apps/products-api/src/app.js';
import { openProductsDatabase } from '../../apps/products-api/src/database.js';
import { listen, ownDatabase, withResources } from '../helpers/resources.js';
import { pactFile } from './paths.js';

test('real Products satisfies the pact generated by Orders', async () => {
  // Missing consumer output is an error, never a silently skipped verification.
  await access(pactFile);

  await withResources(async (resources) => {
    const database = ownDatabase(resources, openProductsDatabase(':memory:'));
    const providerBaseUrl = await listen(resources, buildApp({ database }), 'Pact Products provider');

    await new Verifier({
      provider: 'Products',
      providerBaseUrl,
      pactUrls: [pactFile],
      // Local file only; publishing is disabled by default (no broker needed).
      logLevel: 'warn',
      stateHandlers: {
        'offer-101 exists': async () => {
          // This provider owns its disposable seed; Orders never reads its DB.
          expect(database.resolveOffers(['offer-101']).offers).toHaveLength(1);
        },
      },
    }).verifyProvider();
  });
});
